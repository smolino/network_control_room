"""Read-only catalogue of every trap defined in Cisco's public MIB repository
(https://github.com/cisco/cisco-mibs) - Cisco enterprise MIBs plus the
standard ones Cisco ships (IF-MIB, BGP4-MIB, ISIS-MIB, ...).

Generated by scripts/build_trap_catalog.py into data/trap_catalog.json.
It only names and describes traps; which ones become incidents is still
decided by app.snmp.oid_map.TRAP_OID_MAP.
"""

import json
from functools import lru_cache
from pathlib import Path
from typing import TypedDict

CATALOG_PATH = Path(__file__).with_name("data") / "trap_catalog.json"


class TrapDefinition(TypedDict):
    name: str
    mib: str
    objects: list[str]
    status: str
    description: str


@lru_cache(maxsize=1)
def _catalog() -> dict[str, TrapDefinition]:
    try:
        return json.loads(CATALOG_PATH.read_text(encoding="utf-8"))["traps"]
    except FileNotFoundError:
        return {}


def lookup(oid: str) -> TrapDefinition | None:
    """The MIB definition of a trap OID, or None if no catalogued MIB defines it."""
    return _catalog().get(oid.lstrip("."))


def all_traps() -> dict[str, TrapDefinition]:
    return _catalog()


def size() -> int:
    return len(_catalog())
